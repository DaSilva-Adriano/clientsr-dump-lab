"""Windowed live playback using the same mpv binaries and shaders as dumps.

Encode flags (--o, --ovc, --of, --vo=lavc, --untimed, --no-audio, --hwdec=no)
stay dump-only.

Live decode is split by mode (intentional — two different GPU paths):

- LIVE_NONE: --hwdec=d3d11va --gpu-api=d3d11 (matches vo=gpu-next + d3d11,
  which is what Chrome uses on Windows). Do not pass --hwdec=nvdec here:
  raw CUDA nvdec often fails silently on that VO and mpv stays on software.
  Fallback once: d3d11va-copy, then nvdec-copy. Never stay on hwdec=no
  without a visible log line. No --glsl-shaders, no AnimeJaNai, no --vf=gpu,
  no --untimed. --vo=gpu-next, --force-window=yes, and audio stay on.
- Catalog AI models: --hwdec=nvdec-copy so GLSL / vf=gpu / AnimeJaNai can hook
  the texture. Fallback d3d11va-copy. Do not switch these to plain nvdec.

The extra GPU copy is a cost of hooking client shaders, not of watching the
file. A fair no-AI baseline must not pay that copy.
"""

